import { test, expect } from "../fixtures.ts";
import { logIn, pageErrors } from "../helpers.ts";

test.use({ scenario: "shells" });
test.skip(!process.env.FLORA_SHELL_PREVIEW_IMAGE, "Requires a locally built agent image and Docker");

test("real shell reconnect, resize, exit and tab navigation", async ({ page, backend }) => {
  const errors = pageErrors(page);
  let disconnect: () => Promise<void> = async () => { throw new Error("Shell connection was not established"); };
  await page.routeWebSocket(/\/shells\/[^/]+\/connect/, socket => {
    const server = socket.connectToServer();
    disconnect = async () => { await socket.close(); await server.close(); };
  });
  await logIn(page);
  await page.goto(`${backend.url}/#chats/${backend.chatID}`);
  const draft = page.getByLabel("Follow-up", { exact: true });
  await draft.fill("Keep my draft while I inspect the workspace");
  await page.getByRole("button", { name: "Chat views", exact: true }).click();
  await page.getByRole("menuitem", { name: "New shell", exact: true }).click();
  const terminal = page.getByRole("region", { name: "workspace terminal", exact: true });
  await expect(terminal.getByRole("status")).toHaveText("Connected");
  const input = page.getByLabel("workspace terminal input", { exact: true });
  await input.pressSequentially("export CHECK=preserved; printf 'ready:%s\\n' $$");
  await input.press("Enter");
  await expect(terminal.locator(".xterm-accessibility")).toContainText("ready:");
  await expect(terminal.getByRole("button", { name: "Reconnect", exact: true })).toHaveCount(0);
  await disconnect();
  await expect(terminal.getByRole("status")).toHaveText("Shell disconnected");
  await terminal.getByRole("button", { name: "Reconnect", exact: true }).click();
  await expect(terminal.getByRole("status")).toHaveText("Connected");
  await input.pressSequentially("printf 'reconnected:%s\\n' \"$CHECK\"");
  await input.press("Enter");
  await expect(terminal.locator(".xterm-accessibility")).toContainText("reconnected:preserved");
  await input.press("Shift+Tab");
  await expect(page.getByRole("tab", { name: "workspace", exact: true })).toBeFocused();
  await page.getByRole("tab", { name: "Explore the workspace", exact: true }).click();
  await expect(draft).toHaveValue("Keep my draft while I inspect the workspace");
  await page.getByRole("tab", { name: "workspace", exact: true }).click();
  await page.setViewportSize({ width: 375, height: 812 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await input.pressSequentially("clear; stty size; cat hello.txt");
  await input.press("Enter");
  await expect(terminal.locator(".xterm-accessibility")).toContainText("Welcome to an isolated Flora shell.");
  await input.pressSequentially("mkdir -p '/tmp/folder with spaces'; cd '/tmp/folder with spaces'");
  await input.press("Enter");
  await expect(page.getByRole("tab", { name: "folder with spaces", exact: true })).toBeVisible();
  await page.reload();
  const renamed = page.getByRole("region", { name: "folder with spaces terminal", exact: true });
  await expect(renamed.getByRole("status")).toHaveText("Connected");
  await page.getByLabel("folder with spaces terminal input", { exact: true }).pressSequentially("cd /workspace; printf 'saved:%s\\n' \"$CHECK\"");
  await page.getByLabel("folder with spaces terminal input", { exact: true }).press("Enter");
  await expect(terminal.getByRole("status")).toHaveText("Connected");
  await expect(terminal.locator(".xterm-accessibility")).toContainText("saved:preserved");
  await input.pressSequentially("exit");
  await input.press("Enter");
  await expect(terminal.getByRole("status")).toHaveText("Shell ended");
  await expect(terminal.getByRole("button", { name: "New shell", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Close workspace", exact: true }).click();
  await expect(page.getByRole("tab", { name: "workspace", exact: true })).toHaveCount(0);
  await expect(draft).toHaveValue("Keep my draft while I inspect the workspace");
  expect(errors).toEqual([]);
});

test("machine stop and wake keep old shells ended and never replace the container", async ({ page, backend }) => {
  await logIn(page);
  await page.goto(`${backend.url}/#chats/${backend.chatID}`);
  await expect(page.getByRole("button", { name: "Chat views", exact: true })).toBeVisible();
  const readChat = () => page.evaluate(async id => {
    const response = await fetch(`/api/chats/${id}`);
    if (!response.ok) throw new Error(`Chat read failed: ${response.status}`);
    return response.json();
  }, backend.chatID);
  const before = await readChat();
  await page.getByRole("button", { name: "Chat views", exact: true }).click();
  await page.getByRole("menuitem", { name: "New shell", exact: true }).click();
  const terminal = page.getByRole("region", { name: "workspace terminal", exact: true });
  await expect(terminal.getByRole("status")).toHaveText("Connected");
  await page.getByRole("button", { name: "More chat actions", exact: true }).click();
  await page.getByRole("menuitem", { name: "Stop machine", exact: true }).click();
  await page.keyboard.press("Escape");
  await expect(terminal.getByRole("status")).toHaveText("Machine is asleep");
  await expect(terminal.getByRole("alert")).toHaveCount(0);
  await terminal.getByRole("button", { name: "Wake machine", exact: true }).click();
  const allTerminals = page.getByRole("region", { name: "workspace terminal", exact: true, includeHidden: true });
  await expect(allTerminals.nth(1).getByRole("status")).toHaveText("Connected");
  await page.getByRole("tab", { name: "workspace", exact: true }).first().click();
  await expect(allTerminals.first().getByRole("status")).toHaveText("Shell ended");
  const after = await readChat();
  expect(after.chat.ContainerID).toBe(before.chat.ContainerID);
  await page.goto(`${backend.url}/#chats/${backend.otherChatID}`);
  await page.getByRole("button", { name: "Chat views", exact: true }).click();
  await expect(page.getByRole("menuitem", { name: "New shell", exact: true })).toBeDisabled();
  await expect(page.getByRole("dialog", { name: "Chat views", exact: true }).getByRole("alert")).toHaveCount(0);
});


test("New shell wakes the saved sleeping machine and keeps unavailable actions disabled", async ({ page, backend }) => {
  await logIn(page);
  await page.goto(`${backend.url}/#chats/${backend.chatID}`);
  await expect(page.getByRole("button", { name: "Chat views", exact: true })).toBeVisible();
  const before = await page.evaluate(async id => (await (await fetch(`/api/chats/${id}`)).json()).chat.ContainerID, backend.chatID);
  await page.getByRole("button", { name: "More chat actions", exact: true }).click();
  await page.getByRole("menuitem", { name: "Stop machine", exact: true }).click();
  await expect.poll(() => page.evaluate(async id => (await (await fetch(`/api/chats/${id}/runtime`)).json()).state, backend.chatID)).toBe("stopped");
  await page.getByRole("button", { name: "Chat views", exact: true }).click();
  const menu = page.getByRole("dialog", { name: "Chat views", exact: true });
  await expect(menu.getByRole("menuitem", { name: "New shell", exact: true })).toBeEnabled();
  await menu.getByRole("menuitem", { name: "New shell", exact: true }).click();
  await expect(menu).toHaveCount(0);
  await expect(page.getByRole("region", { name: "workspace terminal", exact: true }).getByRole("status")).toHaveText("Connected");
  const after = await page.evaluate(async id => (await (await fetch(`/api/chats/${id}`)).json()).chat.ContainerID, backend.chatID);
  expect(after).toBe(before);
  await page.route("**/api/chats/*/shells", route => route.request().method() === "POST" ? route.fulfill({status:503,contentType:"application/json",body:JSON.stringify({error:"Could not open a shell"})}) : route.continue());
  await page.getByRole("button", { name: "Chat views", exact: true }).click();
  await menu.getByRole("menuitem", { name: "New shell", exact: true }).click();
  await expect(menu).toHaveCount(0);
  await expect(page.getByText("Could not open a shell", {exact:true})).toBeVisible();
  await page.route("**/api/chats/*/runtime", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: "Machine state unavailable" }) }));
  await page.getByRole("button", { name: "Chat views", exact: true }).click();
  await expect(menu.getByRole("menuitem", { name: /Keep awake/ })).toContainText("Unknown");
  await expect(menu.getByRole("menuitem", { name: "New shell", exact: true })).toBeDisabled();
  await expect(menu.getByRole("alert")).toHaveCount(0);
});
