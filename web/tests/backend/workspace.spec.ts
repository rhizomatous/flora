import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

import { test, expect } from "../fixtures.ts";
import { logIn, assertFitsPhone, pageErrors } from "../helpers.ts";

test.use({ scenario: "workspace" });

test("canvas file tabs preserve repository identity and read without a runtime or implicit wake", async ({ page, backend }) => {
  const errors = pageErrors(page);
  const mutations: string[] = [];
  page.on("request", r => {
    if (r.method() !== "GET" && /\/api\/chats\//.test(r.url())) mutations.push(r.url());
  });
  await logIn(page);
  await page.goto(`${backend.url}/#chats/${backend.chatID}`);
  await page.getByRole("button", { name: "Chat views", exact: true }).click();
  await page.getByRole("menuitem", { name: "Files", exact: true }).click();
  await expect(page.getByRole("tab", { name: "Files", exact: true })).toBeVisible();
  await expect(page.getByRole("complementary", { name: "Side panel" })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Workspace machine" })).toContainText("Missing");
  await page.getByRole("region", { name: "flora/web", exact: true }).getByRole("button", { name: "README.txt", exact: true }).click();
  const web = page.getByRole("region", { name: "flora/web/README.txt preview", exact: true });
  await expect(web.getByLabel("File contents")).toContainText("Repository: flora/web");
  const downloaded = page.waitForEvent("download");
  await web.getByRole("button", { name: "Download", exact: true }).click();
  const download = await downloaded;
  const downloadPath = await download.path();
  assert.ok(downloadPath);
  assert.match(await readFile(downloadPath, "utf8"), /Repository: flora\/web/);
  assert.equal(download.suggestedFilename(), "README.txt");
  await page.getByRole("tab", { name: "Files", exact: true }).click();
  const api = page.getByRole("region", { name: "flora/api", exact: true });
  await api.getByRole("button", { name: "README.txt", exact: true }).click();
  await expect(page.getByRole("region", { name: "flora/api/README.txt preview", exact: true }).getByLabel("File contents")).toContainText("Repository: flora/api");
  await expect(page.getByRole("tab", { name: "flora/web/README.txt", exact: true })).toBeVisible();
  await expect(page.getByRole("tab", { name: "flora/api/README.txt", exact: true })).toBeVisible();
  await page.getByRole("tab", { name: "Files", exact: true }).click();
  await api.getByRole("button", { name: "large.log", exact: true }).click();
  await expect(page.getByText("Showing the first 256 KiB. Download for the full file.", { exact: true })).toBeVisible();
  await page.getByRole("tab", { name: "Files", exact: true }).click();
  await api.getByRole("button", { name: "picture.bin", exact: true }).click();
  await expect(page.getByText("Preview unavailable for binary or non-UTF-8 files.", { exact: true })).toBeVisible();
  await page.getByRole("tab", { name: "Files", exact: true }).click();
  await expect(api.getByRole("button", { name: "outside-link Symlink", exact: true })).toBeDisabled();
  await api.getByRole("button", { name: "empty", exact: true }).click();
  await expect(api.getByText("This folder is empty.", { exact: true })).toBeVisible();
  await page.getByRole("textbox", { name: "Search workspace files", exact: true }).fill("missing-name");
  await expect(page.getByText("No matching files.", { exact: true }).first()).toBeVisible();
  await page.getByRole("textbox", { name: "Search workspace files", exact: true }).fill("navigation.ts");
  await expect(page.getByRole("region", { name: "flora/api search results", exact: true }).getByRole("button", { name: "src/navigation.ts", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("tab", { name: "Files", exact: true })).toBeFocused();
  await assertFitsPhone(page);
  await api.getByRole("button", { name: "src", exact: true }).click();
  await api.getByRole("button", { name: "navigation.ts", exact: true }).click();
  await expect(page.getByRole("button", { name: "Show files", exact: true })).toBeFocused();
  await expect(page.getByRole("region", { name: "flora/api/src/navigation.ts preview", exact: true }).getByLabel("File contents")).toContainText("export const views");
  await page.reload();
  await expect(page.getByRole("region", { name: "flora/api/src/navigation.ts preview", exact: true }).getByLabel("File contents")).toContainText("export const views");
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(mutations, []);
  assert.deepEqual(errors, []);
});

test("highlighted Nix source, numbered lines, icons, and keyboard folder navigation", async ({ page, backend }) => {
  await logIn(page);
  await page.goto(`${backend.url}/#chats/${backend.otherChatID}`);
  await page.getByRole("button", { name: "Chat views", exact: true }).click();
  await page.getByRole("menuitem", { name: "Files", exact: true }).click();
  await expect(page.getByRole("button", { name: "Workspace machine" })).toContainText("Asleep");
  await page.getByRole("button", { name: "flake.nix", exact: true }).click();
  const source = page.getByLabel("File contents", { exact: true });
  await expect(source).toContainText("nixpkgs.url");
  await expect(source.locator("[style*='--shiki-dark']").first()).toBeVisible();
  assert.ok(await source.locator("[data-slot=code-block-line]").count() > 20);
  await expect(page.getByRole("tab", { name: "core/flake.nix", exact: true }).locator("img:visible")).toHaveAttribute("src", /nix/);
  await page.getByRole("tab", { name: "Files", exact: true }).click();
  const folder = page.getByRole("button", { name: "src", exact: true });
  await folder.focus();
  await page.keyboard.press("ArrowRight");
  await expect(folder).toHaveAttribute("aria-expanded", "true");
  await expect(page.getByRole("button", { name: "navigation.ts", exact: true })).toBeVisible();
  await page.keyboard.press("ArrowDown");
  await expect(page.getByRole("button", { name: "navigation.ts", exact: true })).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("region", { name: "core/src/navigation.ts preview", exact: true }).getByLabel("File contents")).toContainText("export const views");
  await page.getByRole("tab", { name: "Files", exact: true }).click();
  await page.keyboard.press("ControlOrMeta+p");
  await expect(page.getByRole("textbox", { name: "Search workspace files" })).toBeFocused();
});

test("narrow main canvas tabs preserve drafts and independent file tabs", async ({ page, backend }) => {
  await logIn(page);
  await page.goto(`${backend.url}/#chats/${backend.otherChatID}`);
  const draft = page.getByLabel("Follow-up", { exact: true });
  await draft.fill("Keep this unsent draft while I inspect files.");
  await page.getByRole("button", { name: "Chat views", exact: true }).click();
  await page.getByRole("menuitem", { name: "Files", exact: true }).click();
  await page.getByRole("button", { name: "src", exact: true }).click();
  await page.getByRole("button", { name: "navigation.ts", exact: true }).click();
  await expect(page.getByLabel("File contents")).toBeVisible();
  await assertFitsPhone(page);
  await expect(page.getByRole("tab", { name: "core/src/navigation.ts", exact: true })).toBeInViewport({ratio:1});
  await page.getByRole("tab", { name: "Files", exact: true }).click();
  await expect(page.getByRole("button", { name: "navigation.ts", exact: true })).toBeVisible();
  await page.getByRole("tab", { name: "core/src/navigation.ts", exact: true }).click();
  await expect(page.getByLabel("File contents")).toBeVisible();
  await page.getByRole("button", { name: "Close Files", exact: true }).focus();
  await page.keyboard.press("Enter");
  await expect(page.getByLabel("File contents")).toBeVisible();
  await page.getByRole("button", { name: "Close core/src/navigation.ts", exact: true }).click();
  await expect(page.getByRole("button", { name: "Explore workspace files", exact: true })).toBeFocused();
  await expect(draft).toHaveValue("Keep this unsent draft while I inspect files.");
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Chat views", exact: true }).click();
  await page.getByRole("menuitem", { name: "Files", exact: true }).click();
  await expect(page.getByRole("button", { name: "navigation.ts", exact: true })).toBeVisible();
  await page.getByRole("tab", { name: "Explore workspace files", exact: true }).click();
  await expect(draft).toHaveValue("Keep this unsent draft while I inspect files.");
});
