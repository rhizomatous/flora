import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

import { test, expect } from "../fixtures.ts";
import { logIn, assertFitsPhone, pageErrors } from "../helpers.ts";

test.use({ scenario: "workspace" });

test("repository files remain readable without a runtime or implicit wake", async ({page,backend})=>{
  const errors=pageErrors(page);
  const mutations:string[]=[];
  page.on("request",r=>{if(r.method() !== "GET" && /\/api\/chats\//.test(r.url()))mutations.push(r.url());});
  await logIn(page);
  await page.goto(`${backend.url}/#chats/${backend.chatID}`);
  await page.getByRole("button",{name:"Chat views",exact:true}).click();
  await page.getByRole("menuitem",{name:"Machine files",exact:true}).click();
  await expect(page.getByText("Machine missing. Reading saved workspace.",{exact:true})).toBeVisible();
  await expect(page.getByLabel("Workspace repository")).toHaveValue("flora/web");
  await page.getByRole("button",{name:"README.txt",exact:true}).click();
  await expect(page.getByLabel("File contents")).toContainText("Repository: flora/web");
  const downloaded=page.waitForEvent("download");
  await page.getByRole("button",{name:"Download",exact:true}).click();
  const download=await downloaded;
  const downloadPath=await download.path();
  assert.ok(downloadPath);
  assert.match(await readFile(downloadPath,"utf8"),/Repository: flora\/web/);
  assert.equal(download.suggestedFilename(),"README.txt");
  await page.getByRole("button",{name:"Back to folder",exact:true}).click();
  await page.getByLabel("Workspace repository").selectOption("flora/api");
  await page.getByRole("button",{name:"README.txt",exact:true}).click();
  await expect(page.getByLabel("File contents")).toContainText("Repository: flora/api");
  await page.getByRole("button",{name:"Back to folder",exact:true}).click();
  await page.getByRole("button",{name:"large.log",exact:true}).click();
  await expect(page.getByText("Showing the first 256 KiB. Download for the full file.",{exact:true})).toBeVisible();
  await expect(page.getByLabel("File contents")).toContainText("Workspace checks passed.");
  await page.getByRole("button",{name:"Back to folder",exact:true}).click();
  await page.getByRole("button",{name:"picture.bin",exact:true}).click();
  await expect(page.getByText("Preview unavailable for binary or non-UTF-8 files.",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Back to folder",exact:true}).click();
  await expect(page.getByRole("button",{name:"outside-link",exact:true})).toBeDisabled();
  await page.getByRole("button",{name:"empty",exact:true}).click();
  await expect(page.getByText("This folder is empty.",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Parent folder",exact:true}).click();
  await page.getByRole("button",{name:"Find in folder",exact:true}).click();
  await page.getByRole("textbox",{name:"Find in folder",exact:true}).fill("missing-name");
  await expect(page.getByText("No matching files in this folder.",{exact:true})).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("button",{name:"Find in folder",exact:true})).toBeFocused();
  await assertFitsPhone(page);
  await page.getByRole("button",{name:"src",exact:true}).click();
  await page.getByRole("button",{name:"navigation.ts",exact:true}).click();
  await expect(page.getByRole("heading",{name:"navigation.ts",exact:true})).toBeFocused();
  await expect(page.getByLabel("File contents")).toContainText("export const views");
  await page.reload();
  await expect(page.getByLabel("File contents")).toContainText("export const views");
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(mutations,[]);
  assert.deepEqual(errors,[]);
});

test("narrow tabs and closing the panel preserve a draft and file navigation",async({page,backend})=>{
  await logIn(page);
  await page.goto(`${backend.url}/#chats/${backend.otherChatID}`);
  const draft=page.getByLabel("Follow-up",{exact:true});
  await draft.fill("Keep this unsent draft while I inspect files.");
  await page.getByRole("button",{name:"Chat views",exact:true}).click();
  await page.getByRole("menuitem",{name:"Machine files",exact:true}).click();
  await expect(page.getByText("Machine asleep. Reading saved workspace.",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"src",exact:true}).click();
  await page.getByRole("button",{name:"navigation.ts",exact:true}).click();
  await expect(page.getByLabel("File contents")).toBeVisible();
  await assertFitsPhone(page);
  await page.getByRole("tab",{name:"Overview",exact:true}).click();
  await page.getByRole("tab",{name:"Machine files",exact:true}).click();
  await expect(page.getByLabel("File contents")).toBeVisible();
  await page.getByRole("button",{name:"Close side panel",exact:true}).click();
  await expect(draft).toHaveValue("Keep this unsent draft while I inspect files.");
  await page.getByRole("button",{name:"Open side panel",exact:true}).click();
  await expect(page.getByLabel("File contents")).toContainText("export const views");
  await page.getByRole("button",{name:"Close Machine files",exact:true}).focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("tab",{name:"Overview",exact:true})).toBeFocused();
  await page.getByRole("button",{name:"Close side panel",exact:true}).click();
  await expect(draft).toHaveValue("Keep this unsent draft while I inspect files.");
});
