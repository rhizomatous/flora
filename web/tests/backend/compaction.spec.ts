import { test, expect } from "../fixtures.ts";
import { logIn, assertFitsPhone, pageErrors } from "../helpers.ts";

test.use({ scenario: "compaction" });

test("model-scoped compaction persists, validates, and explains unsupported limits", async ({ page, backend }, testInfo) => {
  const errors = pageErrors(page);
  await logIn(page);
  await page.goto(`${backend.url}/#chats/${backend.chatID}`);
  await page.getByRole("combobox", { name: "Follow-up", exact: true }).fill("Keep this message draft");
  await page.getByRole("button", { name: "Context usage", exact: true }).click();
  const mode = page.getByLabel("Compact at", { exact: true });
  await expect(mode).toHaveValue("default");
  await mode.selectOption("custom");
  const tokens = page.getByLabel("Tokens", { exact: true });
  await tokens.fill("82001");
  await expect(tokens).toHaveAttribute("aria-invalid", "true");
  await expect(page.getByRole("button", { name: "Save", exact: true })).toBeDisabled();
  await tokens.fill("25000");
  await tokens.focus();
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-desktop.png") });
  await page.setViewportSize({ width: 375, height: 812 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await assertFitsPhone(page);
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-narrow.png") });
  await page.route("**/api/chats/*/compaction", async (route) => { await route.abort("failed"); }, { times: 1 });
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByRole("alert")).toBeVisible();
  await expect(tokens).toHaveValue("25000");
  await page.keyboard.press("Escape");
  await expect(page.getByRole("button", { name: "Context usage", exact: true })).toBeFocused();
  await page.getByRole("button", { name: "Context usage", exact: true }).click();
  await expect(tokens).toHaveValue("25000");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByText("Compaction setting saved. Applies to the next message.")).toBeVisible();
  await expect(page.getByRole("combobox", { name: "Follow-up", exact: true })).toHaveValue("Keep this message draft");
  await expect(page.getByRole("alert")).toHaveCount(0);
  await page.reload();
  await page.getByRole("button", { name: "Context usage", exact: true }).click();
  await expect(mode).toHaveValue("custom");
  await expect(tokens).toHaveValue("25000");
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-saved-narrow.png") });
  await page.setViewportSize({ width: 1280, height: 800 });
  await tokens.focus();
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-saved-desktop.png") });
  await page.evaluate(() => { document.documentElement.classList.remove("dark"); });
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-light-desktop.png") });
  await page.setViewportSize({ width: 375, height: 812 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-light-narrow.png") });
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Send message", exact: true }).click();
  await expect(page.getByText("Saved response 1", { exact: true })).toBeVisible();
  await expect(page.getByText("The saved compaction threshold could not be applied.", { exact: false })).toHaveCount(0);
  // Reject a save after another client selects a different model.
  const origin = new URL(backend.url).origin;
  const detail = await (await page.request.get(`/api/chats/${backend.chatID}`)).json();
  const changed = await page.request.patch(`/api/chats/${backend.chatID}/model`, { headers: { Origin: origin }, data: { execution: { provider: "anthropic", model: "model", variant: "" }, revision: detail.chat.ExecutionRevision } });
  expect(changed.status()).toBe(200);
  const stale = await page.request.patch(`/api/chats/${backend.chatID}/compaction`, { headers: { Origin: origin }, data: { provider: "anthropic", model: "compaction-fixture", threshold: 20000 } });
  expect(stale.status()).toBe(409);
  await page.reload();
  await page.getByRole("button", { name: "Context usage", exact: true }).click();
  await expect(page.getByText("This model has no explicit input limit.", { exact: false })).toBeVisible();
  await expect(mode).toHaveCount(0);
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-unsupported.png") });
  const restored = await page.request.patch(`/api/chats/${backend.chatID}/model`, { headers: { Origin: origin }, data: { execution: { provider: "anthropic", model: "compaction-fixture", variant: "" }, revision: (await changed.json()).ExecutionRevision } });
  expect(restored.status()).toBe(200);
  await page.reload();
  await page.getByRole("button", { name: "Context usage", exact: true }).click();
  await expect(tokens).toHaveValue("25000");
  await page.getByRole("button", { name: "Use default", exact: true }).click();
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(mode).toHaveValue("default");
  expect(errors).toEqual([]);
});
