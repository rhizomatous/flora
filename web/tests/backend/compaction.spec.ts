import type { Route } from "@playwright/test";

import { test, expect } from "../fixtures.ts";
import { logIn, pageErrors } from "../helpers.ts";

test.use({ scenario: "compaction" });

test("compaction row opens a focused dialog with saved settings and draft recovery", async ({ page, backend }, testInfo) => {
  const errors = pageErrors(page);
  await logIn(page);
  await page.goto(`${backend.url}/#chats/${backend.chatID}`);
  const message = page.getByRole("combobox", { name: "Follow-up", exact: true });
  await message.fill("Keep this message draft");
  const trigger = page.getByRole("button", { name: "Context usage", exact: true });
  const row = page.getByRole("button", { name: "Compact at", exact: true });
  const dialog = page.getByRole("dialog", { name: "Compact at", exact: true });
  const field = page.getByRole("textbox", { name: "Tokens", exact: true });
  await trigger.click();
  await expect(row).toHaveText("Compact at82K / 82K");
  await expect(page.getByRole("button", { name: "Save", exact: true })).toHaveCount(0);
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-popover-desktop.png") });
  await page.getByRole("dialog").screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-detail.png") });
  await row.click();
  await expect(dialog).toBeVisible();
  await expect(field).toBeFocused();
  await expect(field).toHaveValue("82,000");
  await expect(page.getByRole("heading", { name: "Context", exact: true })).toHaveCount(0);
  await field.fill("82001");
  await expect(page.getByRole("alert")).toHaveText("Enter 1 to 82,000 tokens.");
  await expect(page.getByRole("button", { name: "Save", exact: true })).toBeDisabled();
  await field.fill("25000");
  await page.route("**/api/chats/*/compaction", async (route) => { await route.abort("failed"); }, { times: 1 });
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByRole("alert")).toBeVisible();
  await expect(field).toHaveValue("25000");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await expect(message).toHaveValue("Keep this message draft");
  await page.reload();
  await trigger.click();
  await expect(row).toHaveText("Compact at25K / 82K");
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-desktop.png") });
  await page.setViewportSize({ width: 375, height: 812 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-narrow.png") });
  await row.click();
  await field.fill("30000");
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await trigger.click(); await row.click();
  await expect(field).toHaveValue("25,000");
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-dialog-narrow.png") });
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-dialog-desktop.png") });
  await page.evaluate(() => { document.documentElement.classList.remove("dark"); });
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-light-desktop.png") });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.screenshot({ animations: "disabled", path: testInfo.outputPath("compaction-light-narrow.png") });
  await page.keyboard.press("Escape");
  await expect(trigger).toBeFocused();
  await page.getByRole("button", { name: "Send message", exact: true }).click();
  await expect(page.getByText("Saved response 1", { exact: true })).toBeVisible();
  const origin = new URL(backend.url).origin;
  const detail = await (await page.request.get(`/api/chats/${backend.chatID}`)).json();
  const changed = await page.request.patch(`/api/chats/${backend.chatID}/model`, { headers: { Origin: origin }, data: { execution: { provider: "anthropic", model: "model", variant: "" }, revision: detail.chat.ExecutionRevision } });
  expect(changed.status()).toBe(200);
  await page.reload(); await trigger.click();
  await expect(row).toBeDisabled();
  await expect(row).toHaveText("Compact at168K");
  await expect(page.getByText("This model has no explicit input limit.", { exact: false })).toHaveCount(0);
  const restored = await page.request.patch(`/api/chats/${backend.chatID}/model`, { headers: { Origin: origin }, data: { execution: { provider: "anthropic", model: "compaction-fixture", variant: "" }, revision: (await changed.json()).ExecutionRevision } });
  expect(restored.status()).toBe(200);
  const missingLimit = async (route: Route) => {
    const response = await route.fetch();
    const body = await response.json();
    await route.fulfill({ response, json: { ...body, maximum: null } });
  };
  // Model discovery can cancel the first request and reload these settings.
  await page.route("**/api/chats/*/compaction", missingLimit);
  await page.reload(); await trigger.click(); await row.click();
  await expect(field).toHaveValue("25,000");
  await expect(field).toBeDisabled();
  await page.unroute("**/api/chats/*/compaction", missingLimit);
  await page.getByRole("button", { name: "Reset to default", exact: true }).click();
  await expect(field).toHaveValue("82,000");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await trigger.click();
  await expect(row).toHaveText("Compact at82K / 82K");
  expect(errors).toEqual([]);
});
