import { test, expect } from "../fixtures.ts";
import { logIn, pageErrors } from "../helpers.ts";
import { detailSchema } from "../../src/chat-schemas";

test.use({ scenario: "chat" });

test("saved organization survives reload while archived execution finishes", async ({ page }, testInfo) => {
  const errors = pageErrors(page);
  await logIn(page);
  await page.getByRole("link", { name: "New chat", exact: true }).click();
  await page.getByRole("button", { name: /^Project:/ }).click();
  await page.getByRole("button", { name: "Browser project", exact: true }).click();
  await page.getByLabel("Message", { exact: true }).fill("Organize running work");
  await page.getByRole("button", { name: "Start chat", exact: true }).click();
  await page.waitForURL(/#chats\/(?!new)/);
  const chatURL = page.url();
  await expect(page.getByRole("form", { name: "Questions", exact: true })).toBeVisible();
  const actions = page.getByRole("button", { name: "More chat actions", exact: true });
  await actions.click();
  await page.getByRole("menuitem", { name: "Rename", exact: true }).click();
  await page.getByRole("textbox", { name: "Chat title", exact: true }).fill("Saved release plan");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await actions.click();
  await page.getByRole("menuitem", { name: "Pin", exact: true }).click();
  await expect(page.getByRole("menu")).toHaveCount(0);
  const nav = page.getByRole("navigation", { name: "Main", exact: true });
  await expect(nav.getByRole("region", { name: "Pinned", exact: true })).toContainText("Saved release plan");
  await actions.click();
  await page.getByRole("menuitem", { name: "Archive", exact: true }).click();
  await expect(page.getByText("Chat archived", { exact: true })).toBeVisible();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(nav.getByRole("link", { name: /Saved release plan/ })).toHaveCount(0);
  await page.getByRole("radio", { name: /^Yes/ }).check();
  await page.getByRole("button", { name: "Answer and continue", exact: true }).click();
  await expect(page.getByText("Saved response 1", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Saved release plan", exact: true })).toBeVisible();
  await expect(page.getByText("Saved response 1", { exact: true })).toBeVisible();
  const id = new URL(chatURL).hash.slice("#chats/".length);
  const detail = detailSchema.parse(await (await page.request.get(`/api/chats/${id}`)).json());
  expect(detail.chat.Archived).toBe(true);
  expect(detail.chat.PinnedAt).toBe("");
  expect(detail.chat.Title).toBe("Saved release plan");
  await page.getByRole("link", { name: "View archived chats", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await expect(page.getByRole("link", { name: "Open chat: Saved release plan", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("backend-archived-mobile.png"), animations: "disabled" });
  await page.getByRole("button", { name: "Actions for Saved release plan", exact: true }).click();
  await page.getByRole("menuitem", { name: "Restore", exact: true }).click();
  await page.getByRole("combobox", { name: "Chat collection", exact: true }).selectOption("current");
  await page.getByRole("link", { name: "Open chat: Saved release plan", exact: true }).click();
  await expect(page.getByText("Saved response 1", { exact: true })).toBeVisible();
  await expect(page.getByText("Archived chat", { exact: true })).toHaveCount(0);
  expect(errors).toEqual([]);
});
