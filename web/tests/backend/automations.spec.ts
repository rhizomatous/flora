import { expect } from "@playwright/test";

import { test } from "../fixtures.ts";
import { assertFitsPhone, logIn, pageErrors } from "../helpers.ts";

test("create, edit, pause, and run an automation in a dedicated chat", async ({ page }, testInfo) => {
  const errors = pageErrors(page);
  await logIn(page);
  await page.getByRole("link", { name: "Automations", exact: true }).click();
  await expect(page.locator("#main-content header").getByRole("heading", { name: "Automations", exact: true })).toBeVisible();
  await page.locator("#main-content header").getByRole("button", { name: "New automation", exact: true }).click();
  const topbar = page.locator("#main-content > header.florets-topbar");
  await expect(topbar.getByRole("heading", { name: "New automation", exact: true })).toBeVisible();
  await expect(topbar.getByRole("button", { name: "Create automation", exact: true })).toBeVisible();
  await page.getByLabel("Name", { exact: true }).fill("Weekly dependency check");
  await page.getByRole("textbox", { name: "Description", exact: true }).fill("Keep dependencies current.");
  await page.getByLabel("Instructions", { exact: true }).fill("Check dependencies and summarize findings.");
  await page.getByLabel("Runs in", { exact: true }).selectOption("same");
  await expect(page.getByLabel("Runs in", { exact: true })).toHaveAccessibleDescription("Continue in the same chat");
  await page.getByRole("combobox", { name: "Schedule", exact: true }).selectOption("weekly");
  await page.getByRole("button", { name: "Friday", exact: true }).click();
  await page.getByRole("button", { name: "Time zone", exact: true }).click();
  await page.getByRole("combobox", { name: "Search time zones" }).fill("New York");
  await page.getByRole("combobox", { name: "Search time zones" }).press("Enter");
  await expect(page.getByRole("button", { name: "Time zone", exact: true })).toHaveText("America/New_York");
  await expect(page.getByRole("textbox", { name: "Instructions", exact: true })).toHaveCSS("resize", "none");
  await expect(page.getByText(/^Next run:/)).toBeVisible();
  await assertFitsPhone(page);
  await page.setViewportSize({ width: 375, height: 600 });
  await page.getByText(/^Next run:/).scrollIntoViewIfNeeded();
  await expect(page.getByRole("button", { name: "Create automation", exact: true })).toBeInViewport({ ratio: 1 });
  await expect(page.getByRole("button", { name: "Cancel", exact: true })).toBeInViewport({ ratio: 1 });
  await page.screenshot({ path: testInfo.outputPath("form-phone.png"), fullPage: false, animations: "disabled" });
  await page.setViewportSize({ width: 1280, height: 1000 });
  await expect(async () => {
    const scheduleBox = await page.getByRole("combobox", { name: "Schedule", exact: true }).boundingBox();
    const zoneBox = await page.getByRole("button", { name: "Time zone", exact: true }).boundingBox();
    expect(Math.abs((scheduleBox?.y ?? -100) - (zoneBox?.y ?? 100))).toBeLessThan(4);
  }).toPass();
  await page.screenshot({ path: testInfo.outputPath("form.png"), fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "Create automation", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Weekly dependency check", exact: true })).toBeVisible();
  await expect(topbar.getByRole("heading", { name: "Weekly dependency check", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Save", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Friday", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("switch", { name: "Active", exact: true }).click();
  await expect(page.getByRole("switch", { name: "Active", exact: true })).not.toBeChecked();
  await page.getByRole("textbox", { name: "Instructions", exact: true }).fill("Review dependencies and summarize findings.");
  await page.getByRole("switch", { name: "Active", exact: true }).click();
  await expect(page.getByRole("switch", { name: "Active", exact: true })).toBeChecked();
  await page.getByRole("switch", { name: "Active", exact: true }).click();
  await expect(page.getByRole("switch", { name: "Active", exact: true })).not.toBeChecked();
  await expect(page.getByRole("textbox", { name: "Instructions", exact: true })).toHaveValue("Review dependencies and summarize findings.");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByRole("button", { name: "Save", exact: true })).toBeDisabled();
  await page.reload();
  await expect(page.getByRole("textbox", { name: "Description", exact: true })).toHaveValue("Keep dependencies current.");
  await expect(page.getByRole("switch", { name: "Active", exact: true })).not.toBeChecked();
  await page.getByRole("textbox", { name: "Instructions", exact: true }).fill("Check dependencies and summarize findings.");
  await page.getByRole("button", { name: "Save and run", exact: true }).click();
  const startedToast = page.locator("[data-sonner-toast]").filter({ hasText: "Run started" });
  await expect(startedToast).toContainText("Weekly dependency check");
  await expect(startedToast.getByRole("button", { name: "Open chat", exact: true })).toBeVisible();
  await expect(startedToast).toHaveAttribute("data-type", "success");
  await expect(page.getByRole("region", { name: "Run history", exact: true }).getByRole("link", { name: "Open chat", exact: true })).toHaveCount(1);
  const firstLink = await page.getByRole("region", { name: "Run history", exact: true }).getByRole("link", { name: "Open chat", exact: true }).getAttribute("href");
  await page.screenshot({ path: testInfo.outputPath("history.png"), fullPage: true, animations: "disabled" });
  await startedToast.getByRole("button", { name: "Open chat", exact: true }).click();
  await expect(page.getByRole("link", { name: "Automation run", exact: true })).toBeVisible();
  await page.getByRole("radio", { name: /^Yes/ }).click();
  await page.getByRole("button", { name: "Answer and continue", exact: true }).click();
  await page.getByText("Saved response 1", { exact: true }).waitFor();
  await page.getByRole("link", { name: "Automation run", exact: true }).click();
  await expect(page.getByText("completed", { exact: true })).toBeVisible({ timeout: 15000 });
  await page.getByRole("button", { name: "Run now", exact: true }).click();
  await expect(page.getByRole("region", { name: "Run history", exact: true }).getByRole("link", { name: "Open chat", exact: true })).toHaveCount(2);
  const secondLink = await page.getByRole("region", { name: "Run history", exact: true }).getByRole("link", { name: "Open chat", exact: true }).first().getAttribute("href");
  expect(secondLink?.split("?")[0]).toBe(firstLink?.split("?")[0]);
  expect(secondLink).not.toBe(firstLink);
  await page.getByLabel("Runs in", { exact: true }).selectOption("new");
  await expect(page.getByLabel("Runs in", { exact: true })).toHaveAccessibleDescription("Start a new chat each run");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByLabel("Runs in", { exact: true })).toHaveValue("new");
  await page.getByRole("switch", { name: "Active", exact: true }).click();
  await expect(page.getByRole("switch", { name: "Active", exact: true })).toBeChecked();
  await expect(page.locator("[data-sonner-toast]")).toHaveCount(0, { timeout: 12000 });
  await page.getByRole("link", { name: "Automations", exact: true }).last().click();
  const table = page.getByRole("list", { name: "Active automations", exact: true });
  await expect(table.getByRole("link", { name: "Open automation: Weekly dependency check", exact: true })).toBeVisible();
  await page.getByRole("button", { name: /^Inactive/ }).click();
  await expect(page.getByText("No automations match these filters.")).toBeVisible();
  await page.getByRole("button", { name: "Show all automations" }).click();
  await page.getByRole("button", { name: "Search automations", exact: true }).click();
  await page.getByRole("textbox", { name: "Search automations", exact: true }).fill("no-match");
  await expect(page.getByText("No automations match these filters.")).toBeVisible();
  await page.getByRole("textbox", { name: "Search automations", exact: true }).fill("Keep dependencies current");
  await expect(table.getByRole("link", { name: "Open automation: Weekly dependency check", exact: true })).toBeVisible();
  await page.locator("summary").filter({ hasText: "Active" }).click();
  await expect(table).not.toBeVisible();
  await page.locator("summary").filter({ hasText: "Active" }).click();
  await expect(table).toBeVisible();
  await assertFitsPhone(page);
  await page.screenshot({ path: testInfo.outputPath("automation-list.png"), fullPage: true });
  expect(errors).toEqual([]);
});
